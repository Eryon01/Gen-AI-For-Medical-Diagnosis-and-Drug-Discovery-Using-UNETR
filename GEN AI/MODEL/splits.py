"""
Deterministic train/val/test split generation.
Splits are generated by case ID to ensure reproducibility.
"""

import json
from pathlib import Path
from typing import List, Dict, Tuple
import hashlib
import numpy as np
from datetime import datetime


class SplitGenerator:
    """Generate deterministic train/val/test splits."""
    
    def __init__(self, seed: int = 42):
        """Initialize split generator with seed for reproducibility."""
        self.seed = seed
        np.random.seed(seed)
    
    def _case_id_to_hash(self, case_id: str, seed: int) -> float:
        """Convert case ID to deterministic hash in [0, 1)."""
        # Use case_id and seed to create a deterministic value
        combined = f"{case_id}_{seed}"
        hash_val = hashlib.md5(combined.encode()).digest()
        # Convert first 8 bytes to float in [0, 1)
        hash_int = int.from_bytes(hash_val[:8], 'big')
        return (hash_int % (2**32)) / (2**32)
    
    def split_by_case_id(self, case_ids: List[str], 
                        train_ratio: float = 0.7,
                        val_ratio: float = 0.15,
                        test_ratio: float = 0.15) -> Dict[str, List[str]]:
        """
        Split cases deterministically by case ID.
        Ratios should sum to 1.0.
        """
        # Validate ratios
        total = train_ratio + val_ratio + test_ratio
        assert abs(total - 1.0) < 1e-6, f"Ratios must sum to 1.0, got {total}"
        
        # Create deterministic hash for each case
        case_hashes = [(case_id, self._case_id_to_hash(case_id, self.seed)) 
                       for case_id in case_ids]
        
        # Sort by hash for reproducibility
        case_hashes.sort(key=lambda x: x[1])
        
        # Split
        n = len(case_ids)
        n_train = int(n * train_ratio)
        n_val = int(n * val_ratio)
        
        train = [c[0] for c in case_hashes[:n_train]]
        val = [c[0] for c in case_hashes[n_train:n_train + n_val]]
        test = [c[0] for c in case_hashes[n_train + n_val:]]
        
        return {
            "train": sorted(train),
            "val": sorted(val),
            "test": sorted(test),
        }
    
    def save_splits(self, splits: Dict[str, List[str]], filepath: Path) -> None:
        """Save splits to JSON file."""
        filepath.parent.mkdir(parents=True, exist_ok=True)
        
        splits_data = {
            "timestamp": datetime.now().isoformat(),
            "seed": self.seed,
            "splits": splits,
            "counts": {
                "train": len(splits["train"]),
                "val": len(splits["val"]),
                "test": len(splits["test"]),
            }
        }
        
        with open(filepath, 'w') as f:
            json.dump(splits_data, f, indent=2)
        
        print(f"Splits saved to {filepath}")
    
    @staticmethod
    def load_splits(filepath: Path) -> Dict[str, List[str]]:
        """Load splits from JSON file."""
        with open(filepath, 'r') as f:
            data = json.load(f)
        return data["splits"]
    
    @staticmethod
    def print_splits(splits: Dict[str, List[str]]) -> None:
        """Print split statistics."""
        print("\n" + "="*60)
        print("DATA SPLIT SUMMARY")
        print("="*60)
        for split_name, cases in splits.items():
            ratio = len(cases) / (len(splits["train"]) + len(splits["val"]) + len(splits["test"]))
            print(f"{split_name:6s}: {len(cases):4d} cases ({ratio:.1%})")
        print("="*60)


